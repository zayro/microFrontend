export const ProductService = {
  getProductsData() {
    return [
      {
        nombre_entidad: '',
        tipo_producto: '',
        image: '',
        numero_producto: '',
        ciudad: '',
        pais: '',
        moneda: '',
        monto: 0,
      },
    ]
  },

  getProductsMini() {
    return Promise.resolve(this.getProductsData().slice(0, 5))
  },

  getProductsSmall() {
    return Promise.resolve(this.getProductsData().slice(0, 10))
  },

  getProducts() {
    return Promise.resolve(this.getProductsData())
  },
}

export const PepService = {
  getPepData() {
    return [
      {
        nombre_completo: '',
        tipo_identificacion: '',
        numero_identificacion: 0,
        parentesco: '',
        descripcion_pep: '',
      },
    ]
  },

  getMini() {
    return Promise.resolve(this.getPepData().slice(0, 5))
  },

  getSmall() {
    return Promise.resolve(this.getPepData().slice(0, 10))
  },

  getAll() {
    return Promise.resolve(this.getPepData())
  },

  getCreateData(number) {
    const baseData = this.getPepData()[0]
    const data = Array.from({ length: number }, (_, i) => ({
      ...baseData,
    }))
    return Promise.resolve(data)
  },
}
